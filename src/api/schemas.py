"""Response schemas of the API, for the documentation and for the TypeScript types of the React frontend
(frontend/src/api/schema.d.ts, generated by openapi-typescript from frontend/src/api/openapi.json).

They DESCRIBE the JSON the routes already return: main.py passes them as `responses={200: {"model": ...}}`, so FastAPI
documents them without filtering or validating the answers (the JSON sent is exactly the one built by the agents).
tests/api/test_api.py validates real answers against them (extra fields forbidden), so a field added by the agents
without being declared here makes a test fail: the frontend types stay in sync.
"""
from typing import Any, Dict, List, Literal, Optional, Tuple

from pydantic import BaseModel, ConfigDict


class Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class Health(Strict):
    statut: str
    modeles: List[str]
    device: str
    mode_test: bool = False
    admin: bool = False


class Gouvernorat(Strict):
    fr: str
    ar: str


class Culture(Strict):
    code: str
    fr: str
    ar: str


class CropChoice(Strict):
    code: str
    fr: str
    confiance: float


class VlmOpinion(Strict):
    culture: str
    conf_culture: Optional[float] = None
    probleme: Optional[str] = None
    conf_probleme: Optional[float] = None
    symptomes: Optional[str] = None


class Identify(Strict):
    """POST /identify. Without a leaf (photo_plante false, or a fruit) only the first three fields are given."""
    feuille: bool
    photo_plante: bool
    routage: str
    culture: Optional[str] = None
    fr: Optional[str] = None
    ar: Optional[str] = None
    confiance: Optional[float] = None
    sure: Optional[bool] = None
    autre_plante: Optional[bool] = None
    avis: Optional[Dict[str, Optional[str]]] = None
    accord: Optional[int] = None
    n_avis: Optional[int] = None
    vlm: Optional[VlmOpinion] = None
    source_culture: Optional[str] = None
    desaccord_vlm: Optional[bool] = None
    top3: Optional[List[CropChoice]] = None


class OtherModel(Strict):
    classe: Optional[str] = None
    confiance: Optional[float] = None


class Diagnostic(Strict):
    routing: Optional[str] = None
    task: Optional[str] = None
    classe: Optional[str] = None
    nom: Optional[str] = None
    confiance: Optional[float] = None
    fiable: Optional[bool] = None
    raisons_doute: Optional[List[str]] = None
    top3: Optional[List[Tuple[str, float]]] = None
    autre_modele: Optional[OtherModel] = None
    choix_du_modele: Optional[str] = None
    niveau: Optional[Literal["sur", "probable", "incertain"]] = None


class CropInfo(Strict):
    """The crop of the answer: the code used and what the Identification agent saw on the photo."""
    code: Optional[str] = None
    source: Optional[str] = None
    predite: Optional[str] = None
    confiance: Optional[float] = None
    top3: Optional[List[Tuple[str, float]]] = None
    avis: Optional[Dict[str, Optional[str]]] = None
    accord: Optional[int] = None
    n_avis: Optional[int] = None
    source_culture: Optional[str] = None
    desaccord_vlm: Optional[bool] = None
    contradiction: Optional[bool] = None
    inconnue: Optional[bool] = None
    proposee: Optional[str] = None
    non_couverte: Optional[bool] = None


class Product(Strict):
    nom: str
    dose: Optional[str] = None
    dar_jours: Optional[int] = None


class Fertiliser(Strict):
    nom: str


class Source(Strict):
    fiche: str
    lien: str
    licence: Optional[str] = None
    fiche_id: Optional[str] = None
    section: Optional[str] = None


class Verification(Strict):
    valide: bool
    raisons: List[str]
    avertissements: List[str]
    produits_verifies: List[Dict[str, Any]]
    secours: Optional[bool] = None


class TraceStep(Strict):
    agent: str
    action: str
    duree_ms: int


class CardLine(Strict):
    """A line of a registered product, exactly as in the text; url: the page of a validated shop offer."""
    role: Literal["produit", "dose_pratique", "lmr", "boutique", "boutique_absente", "pourquoi"]
    texte: str
    url: Optional[str] = None


class CardProduct(Strict):
    nom: str
    lignes: List[CardLine]


class Card(Strict):
    """A section of the answer. Joined by a blank line, the "texte" of the cards ARE the answer text (checked by the
    Vérificateur): the app shows them as cards without changing a character."""
    type: Literal["autre_photo", "doute", "pistes", "questions", "crda", "sain", "hypothese", "diagnostic",
                  "traitements", "ecartes", "rotation", "securite", "a_savoir", "aucun_produit", "affiner",
                  "prevention", "conseils", "sources", "engrais", "eau", "fin", "texte"]
    texte: str
    titre: Optional[str] = None
    elements: Optional[List[str]] = None
    produits: Optional[List[CardProduct]] = None
    champs: Optional[List[str]] = None
    citations: Optional[List[str]] = None
    sources: Optional[List[str]] = None


class Diagnose(Strict):
    """POST /diagnose. `texte` is the answer written by code and checked by the Vérificateur: the app shows it as is."""
    issue: Literal["conseil", "question", "autre_photo", "crda"]
    texte: str
    langue: Literal["fr", "ar"]
    cartes: List[Card]
    diagnostic: Optional[Diagnostic] = None
    culture: Optional[CropInfo] = None
    produits: List[Product]
    engrais: List[Fertiliser]
    avertissements: List[str]
    questions: List[str]
    sources: List[Source]
    verification: Verification
    contexte: Dict[str, Any]
    questions_contexte: List[str]
    trace: List[TraceStep]
    duree_s: float
    journal_id: Optional[str] = None


class FeedbackSaved(Strict):
    statut: str


class JournalRow(Strict):
    id: str
    date: str
    culture: Optional[str] = None
    gouvernorat: Optional[str] = None
    langue: Optional[str] = None
    issue: Optional[str] = None
    classe: Optional[str] = None
    maladie: Optional[str] = None
    confiance: Optional[float] = None
    fiable: Optional[bool] = None
    produits: str = ""
    verdict: Optional[Literal["correct", "partiel", "faux"]] = None
    vraie_culture: Optional[str] = None
    vrai_probleme: Optional[str] = None
    vraie_reponse: Optional[str] = None
    commentaire: Optional[str] = None
    garder_photo: Optional[bool] = None
    photo: bool = False


class CropStats(Strict):
    culture: str
    analyses: int
    avec_avis: int
    correct: int
    partiel: int
    faux: int
    precision: Optional[float] = None


class AdminJournal(Strict):
    """GET /admin/journal: the analyses of the test journal (newest first) and the accuracy per crop."""
    analyses: List[JournalRow]
    par_culture: List[CropStats]


def doc(model):
    """`responses=` argument of a route: the schema in the documentation, the answer not filtered."""
    return {200: {"model": model, "description": "Réponse"}}
